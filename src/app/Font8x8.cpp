void BuildFontAtlas(std::vector<uint8_t> &coverage,FontInfo &font) {

  font.glyphW = 8;
  font.glyphH = 8;
  font.atlasW = 16 * 8;
  font.atlasH = 6 * 8;
  coverage.assign((size_t)font.atlasW * font.atlasH,0);

  for(int c=32;c<128;c++) {
    int x0 = ((c-32) % 16) * 8, y0 = ((c-32) / 16) * 8;
    for(int y=0;y<8;y++)
      for(int x=0;x<8;x++) {
        // Character 127: solid cell used for filled shapes
        bool on = c<127 ? glyphs[c-32][y][x]=='#' : true;
        coverage[(size_t)(y0+y) * font.atlasW + x0 + x] = on ? 255 : 0;
      }
  }

}

